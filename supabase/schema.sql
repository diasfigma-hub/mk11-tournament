-- MK11 Arena — схема Supabase.
-- Выполните этот файл в Supabase → SQL Editor на чистом проекте.
-- Скрипт создаёт таблицы, ограничения, RLS-политики и публичный счётчик участников.
-- Повторный запуск безопасен: таблицы/индексы создаются с IF NOT EXISTS, политики пересоздаются.

-- ── Участники ────────────────────────────────────────────────────────────────

create table if not exists public.participants (
  id bigint generated by default as identity primary key,
  nickname text not null,
  full_name text not null,
  main_character text not null,
  contact text,
  status text not null default 'accepted',
  created_at timestamptz not null default now(),

  constraint participants_nickname_len
    check (char_length(btrim(nickname)) between 2 and 20),
  constraint participants_full_name_len
    check (char_length(btrim(full_name)) between 2 and 120),
  constraint participants_contact_len
    check (contact is null or char_length(contact) <= 120),
  constraint participants_status_allowed
    check (status in ('accepted', 'pending', 'disqualified')),
  -- Только 24 персонажа базовой версии MK11. DLC сюда попасть не может.
  constraint participants_character_allowed
    check (
      main_character in (
        'Baraka', 'Cassie Cage', 'Cetrion', 'D''Vorah', 'Erron Black', 'Frost',
        'Geras', 'Jacqui Briggs', 'Jade', 'Jax Briggs', 'Johnny Cage', 'Kabal',
        'Kano', 'Kitana', 'Kollector', 'Kotal Kahn', 'Kung Lao', 'Liu Kang',
        'Noob Saibot', 'Raiden', 'Scorpion', 'Skarlet', 'Sonya Blade', 'Sub-Zero'
      )
    )
);

-- Ник уникален без учёта регистра и пробелов по краям — защита от повторной заявки.
create unique index if not exists participants_nickname_unique
  on public.participants (lower(btrim(nickname)));

create index if not exists participants_created_at_idx
  on public.participants (created_at desc);

-- ── Турниры ──────────────────────────────────────────────────────────────────

create table if not exists public.tournaments (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  date timestamptz,
  registration_end timestamptz,
  player_limit integer,
  platform text,
  bo integer not null default 3,
  final_bo integer not null default 5,
  format text not null default 'single_elimination',
  status text not null default 'draft',
  players jsonb not null default '[]'::jsonb,
  rounds jsonb not null default '[]'::jsonb,
  third_place jsonb,
  champion jsonb,
  registration_closed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint tournaments_title_len check (char_length(btrim(title)) between 1 and 120),
  constraint tournaments_status_allowed check (status in ('draft', 'live', 'finished')),
  constraint tournaments_bo_allowed check (bo in (3, 5)),
  constraint tournaments_final_bo_allowed check (final_bo in (3, 5)),
  constraint tournaments_player_limit_allowed
    check (player_limit is null or player_limit between 2 and 64)
);

-- ── Глобальные настройки лобби ──────────────────────────────────────────────

create table if not exists public.settings (
  id smallint primary key default 1,
  registration_closed boolean not null default false,
  updated_at timestamptz not null default now(),

  constraint settings_single_row check (id = 1)
);

insert into public.settings (id) values (1)
on conflict (id) do nothing;

-- ── Администраторы ──────────────────────────────────────────────────────────
-- Даже если в Supabase Auth случайно включат регистрацию, админские права
-- получит только пользователь, добавленный сюда вручную.

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;
revoke all on table public.admin_users from anon, authenticated;

-- ── Права доступа ────────────────────────────────────────────────────────────

alter table public.participants enable row level security;
alter table public.tournaments enable row level security;
alter table public.settings enable row level security;

revoke all on table public.participants from anon, authenticated;
revoke all on table public.tournaments from anon, authenticated;
revoke all on table public.settings from anon, authenticated;

grant usage on schema public to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- Заявку может отправить и аноним, и вошедший пользователь (например, если
-- организатор в этом же браузере открыл публичную форму). Колонки status и
-- created_at недоступны для записи — работают значения по умолчанию.
grant insert (nickname, full_name, main_character, contact)
  on public.participants to anon, authenticated;

-- Администратор видит контакты и управляет записями.
grant select, update, delete on public.participants to authenticated;

-- Турниры и настройки читаются публично, меняются только администратором.
grant select on public.tournaments to anon;
grant select, insert, update, delete on public.tournaments to authenticated;

grant select on public.settings to anon;
grant select, update on public.settings to authenticated;

-- ── RLS-политики ─────────────────────────────────────────────────────────────

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.admin_users where user_id = auth.uid()
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

drop policy if exists participants_admin_select on public.participants;
create policy participants_admin_select
  on public.participants for select
  to authenticated
  using (public.is_admin());

drop policy if exists participants_public_insert on public.participants;
create policy participants_public_insert
  on public.participants for insert
  to anon, authenticated
  with check (
    status = 'accepted'
    and coalesce(
      (select registration_closed from public.settings where id = 1),
      false
    ) = false
  );

drop policy if exists participants_admin_update on public.participants;
create policy participants_admin_update
  on public.participants for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists participants_admin_delete on public.participants;
create policy participants_admin_delete
  on public.participants for delete
  to authenticated
  using (public.is_admin());

drop policy if exists tournaments_public_select on public.tournaments;
create policy tournaments_public_select
  on public.tournaments for select
  to anon, authenticated
  using (true);

drop policy if exists tournaments_admin_insert on public.tournaments;
create policy tournaments_admin_insert
  on public.tournaments for insert
  to authenticated
  with check (public.is_admin());

drop policy if exists tournaments_admin_update on public.tournaments;
create policy tournaments_admin_update
  on public.tournaments for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists tournaments_admin_delete on public.tournaments;
create policy tournaments_admin_delete
  on public.tournaments for delete
  to authenticated
  using (public.is_admin());

drop policy if exists settings_public_select on public.settings;
create policy settings_public_select
  on public.settings for select
  to anon, authenticated
  using (true);

drop policy if exists settings_admin_update on public.settings;
create policy settings_admin_update
  on public.settings for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- ── Публичный счётчик участников ────────────────────────────────────────────
-- Нужен главной странице и форме регистрации. Возвращает только число,
-- поэтому контакты и остальные данные анонимам не раскрываются.

create or replace function public.participant_count()
returns integer
language sql
security definer
set search_path = public
stable
as $$
  select count(*)::integer from public.participants;
$$;

revoke all on function public.participant_count() from public;
grant execute on function public.participant_count() to anon, authenticated;

-- ── Realtime для админ-панели ───────────────────────────────────────────────
-- Аноним не имеет SELECT-политики на participants, поэтому изменения получает
-- только вошедший администратор.

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'participants'
    ) then
      alter publication supabase_realtime add table public.participants;
    end if;
  end if;
end
$$;
